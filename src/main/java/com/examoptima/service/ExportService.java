package com.examoptima.service;

import com.examoptima.model.AllocationPlan;
import com.examoptima.model.HallAllocation;
import com.examoptima.model.SeatAllocation;
import com.examoptima.util.CsvUtil;
import com.examoptima.util.PdfUtil;

import java.io.IOException;
import java.util.ArrayList;
import java.util.List;

/**
 * Advanced Java: Export Service.
 * Generates:
 *  1. CSV Export of all seat allocations.
 *  2. PDF Seating Chart per hall.
 *  3. PDF Invigilator Duty Sheet with signature boxes.
 *  4. PDF Hall-wise Attendance Sheet.
 */
public class ExportService {

    public static String exportAllocationsCsv(AllocationPlan plan) {
        if (plan == null) return "No allocation data available.";

        StringBuilder sb = new StringBuilder();
        sb.append(CsvUtil.formatRow(List.of(
            "Exam ID", "Exam Name", "Subject Code", "Hall Name", "Room No", "Building",
            "Seat No", "Row", "Col", "USN", "Student Name", "Department", "Subject", "Color Group"
        ))).append("\n");

        for (HallAllocation hall : plan.getHalls()) {
            for (SeatAllocation seat : hall.getSeats()) {
                sb.append(CsvUtil.formatRow(List.of(
                    plan.getExamId(),
                    plan.getExamName(),
                    plan.getSubjectCode(),
                    hall.getName(),
                    hall.getRoom(),
                    hall.getBuilding(),
                    String.valueOf(seat.getSeat()),
                    String.valueOf(seat.getRow()),
                    String.valueOf(seat.getCol()),
                    seat.getUsn(),
                    seat.getName(),
                    seat.getDepartment(),
                    seat.getSubject() != null ? seat.getSubject() : "",
                    String.valueOf(seat.getColorGroup())
                ))).append("\n");
            }
        }

        return sb.toString();
    }

    public static byte[] exportRoomSeatingPdf(AllocationPlan plan, String roomId) throws IOException {
        HallAllocation targetHall = findHall(plan, roomId);
        String title = "ExamOptima - Seating Chart";
        String subtitle = String.format("Exam: %s (%s) | Hall: %s (Room %s, %s)",
            plan != null ? plan.getExamName() : "N/A",
            plan != null ? plan.getSubjectCode() : "N/A",
            targetHall != null ? targetHall.getName() : "All Halls",
            targetHall != null ? targetHall.getRoom() : "-",
            targetHall != null ? targetHall.getBuilding() : "-"
        );

        String[] headers = {"Seat #", "USN", "Student Name", "Department", "Subject", "Color Group"};
        List<String[]> rows = new ArrayList<>();

        if (targetHall != null) {
            for (SeatAllocation s : targetHall.getSeats()) {
                rows.add(new String[]{
                    String.valueOf(s.getSeat()),
                    s.getUsn(),
                    s.getName(),
                    s.getDepartment(),
                    s.getSubject() != null ? s.getSubject() : "-",
                    "Group " + s.getColorGroup()
                });
            }
        }

        String notice = "Generated by ExamOptima Advanced Java Engine. Verified without neighbor conflicts.";
        return PdfUtil.createDocument(title, subtitle, rows, headers, notice);
    }

    public static byte[] exportInvigilatorSheetPdf(AllocationPlan plan, String roomId) throws IOException {
        HallAllocation targetHall = findHall(plan, roomId);
        String title = "ExamOptima - Invigilator Duty Sheet";
        String subtitle = String.format("Exam: %s | Room: %s | Total Candidates: %d",
            plan != null ? plan.getExamName() : "N/A",
            targetHall != null ? targetHall.getName() + " (Room " + targetHall.getRoom() + ")" : "All",
            targetHall != null ? targetHall.getSeats().size() : 0
        );

        String[] headers = {"Seat #", "USN", "Candidate Name", "Booklet No.", "Student Sign", "Invigilator Initial"};
        List<String[]> rows = new ArrayList<>();

        if (targetHall != null) {
            for (SeatAllocation s : targetHall.getSeats()) {
                rows.add(new String[]{
                    String.valueOf(s.getSeat()),
                    s.getUsn(),
                    s.getName(),
                    "[__________]",
                    "[__________]",
                    "[____]"
                });
            }
        }

        String notice = "Chief Superintendent Signature: _______________________   Date: ______________";
        return PdfUtil.createDocument(title, subtitle, rows, headers, notice);
    }

    public static byte[] exportAttendanceSheetPdf(AllocationPlan plan, String roomId) throws IOException {
        HallAllocation targetHall = findHall(plan, roomId);
        String title = "ExamOptima - Official Attendance Register";
        String subtitle = String.format("Examination: %s (%s) | Room %s",
            plan != null ? plan.getExamName() : "N/A",
            plan != null ? plan.getSubjectCode() : "-",
            targetHall != null ? targetHall.getRoom() + " (" + targetHall.getName() + ")" : "All"
        );

        String[] headers = {"#", "USN", "Candidate Name", "Dept", "Present [P]", "Absent [A]", "Remarks"};
        List<String[]> rows = new ArrayList<>();

        if (targetHall != null) {
            int idx = 1;
            for (SeatAllocation s : targetHall.getSeats()) {
                rows.add(new String[]{
                    String.valueOf(idx++),
                    s.getUsn(),
                    s.getName(),
                    s.getDepartment(),
                    "[   ]",
                    "[   ]",
                    "Seat #" + s.getSeat()
                });
            }
        }

        String notice = "Room Invigilator Signature: ______________________ Total Present: _____ Total Absent: _____";
        return PdfUtil.createDocument(title, subtitle, rows, headers, notice);
    }

    private static HallAllocation findHall(AllocationPlan plan, String roomId) {
        if (plan == null || plan.getHalls().isEmpty()) return null;
        if (roomId == null || roomId.isEmpty() || "ALL".equalsIgnoreCase(roomId)) {
            return plan.getHalls().get(0);
        }
        for (HallAllocation h : plan.getHalls()) {
            if (h.getClassroomId().equalsIgnoreCase(roomId) || h.getRoom().equalsIgnoreCase(roomId)) {
                return h;
            }
        }
        return plan.getHalls().get(0);
    }
}
